//! P1 rule-based audit (找碴): deterministic, zero-token checks over both vaults.
//!
//! Every problem becomes an [`Issue`] with a stable fingerprint. With `write_findings`, issues
//! become `finding` notes that humans review in Obsidian (`_system/Findings.base`):
//! - a new problem creates `Findings/audit-<rule>-<note>-<fp>.md` (status `open`);
//! - an open/accepted finding whose problem is gone is closed (`fixed`) automatically;
//! - a `fixed` finding whose problem comes back is reopened;
//! - a finding a human set to `rejected` is remembered in `_system/audit-suppressions.toml`
//!   and never reported again, even if the finding note is later deleted.

