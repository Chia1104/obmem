#[cfg_attr(feature = "clap", derive(clap::ValueEnum))]
#[serde(rename_all = "lowercase")]
pub enum Severity {
    Info,
    Warn,
    Error,
}

impl Severity {
    pub fn as_str(self) -> &'static str {
        match self {
            Severity::Info => "info",
            Severity::Warn => "warn",
            Severity::Error => "error",
        }
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct Issue {
    pub rule: &'static str,
    pub severity: Severity,
    pub scope: &'static str,
    /// Vault-relative path of the note the problem is in.
    pub path: String,
    pub note_id: String,
    pub message: String,
    pub fix: String,
    /// The other note involved (link target, duplicate twin), if any.
    pub related: Option<String>,
    pub fingerprint: String,
}

pub struct AuditOptions {
    /// `None` audits both vaults.
    pub scope: Option<crate::note::Scope>,
    /// Empty runs every rule.
    pub rules: Vec<String>,
    pub today: NaiveDate,
}

